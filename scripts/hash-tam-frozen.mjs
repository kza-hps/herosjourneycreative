// Prebuild script — computes SHA-256 of the frozen valence tables and writes
// the hash into lib/tam/generated-hash.ts so PREREG.configHash is accurate.
import { createHash } from "crypto";
import { readFileSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { join, dirname } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const valences = JSON.parse(
  readFileSync(join(root, "lib/tam/valences.json"), "utf8")
);

const canonical = JSON.stringify({ tarot: valences.tarot, suit: valences.suit });
const hash = createHash("sha256").update(canonical).digest("hex");

const out = `// auto-generated by scripts/hash-tam-frozen.mjs — do not edit\nexport const CONFIG_HASH = "${hash}";\n`;

writeFileSync(join(root, "lib/tam/generated-hash.ts"), out, "utf8");
console.log("TAM frozen config hash:", hash);
